import Foundation

/// 介面語言：偏好語言是中文就用中文，其他一律英文。
/// 先看 App 自己的語言設定（系統設定「語言與地區」的 App 個別語言），命令列從連結啟動時也讀得到。
enum Lang {
    static var english: Bool = {
        let own = UserDefaults(suiteName: "com.zilong.SmallImg")?.stringArray(forKey: "AppleLanguages")?.first
        return !(own ?? Locale.preferredLanguages.first ?? "").hasPrefix("zh")
    }()
}

/// 介面字串。以中文原文當 key，英文介面時查 `englishStrings`；%@ 依序代入 args。
func L(_ zh: String, _ args: Any...) -> String {
    let template = Lang.english ? (englishStrings[zh] ?? zh) : zh
    guard !args.isEmpty else { return template }
    var parts = template.components(separatedBy: "%@")
    var out = parts.removeFirst()
    for (i, p) in parts.enumerated() {
        out += i < args.count ? "\(args[i])" : ""
        out += p
    }
    return out
}

